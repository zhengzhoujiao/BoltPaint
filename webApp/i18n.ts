const i18n = i18next.default ? i18next.default : i18next;

// 从 localStorage 读取保存的语言设置，如果没有则使用默认值
const getSavedLanguage = (): string => {
  const savedLang = localStorage.getItem('i18n_language');
  return savedLang && (savedLang === 'zh' || savedLang === 'en') ? savedLang : 'zh';
};

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: getSavedLanguage(), // 使用保存的语言设置
    interpolation: {
      escapeValue: false
    }
  });

// 监听语言变化，保存到 localStorage
i18n.on('languageChanged', (lng) => {
  localStorage.setItem('i18n_language', lng);
});

